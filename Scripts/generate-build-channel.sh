#!/usr/bin/env bash
# Writes PostcardFilm/Support/BuildChannel.generated.swift from the current git branch.
# Film debug picker is visible only when DEBUG && isTestBranch.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${ROOT}/PostcardFilm/Support/BuildChannel.generated.swift"

BRANCH="${BUILD_CHANNEL_BRANCH:-$(git -C "${ROOT}" rev-parse --abbrev-ref HEAD 2>/dev/null || echo unknown)}"
# Escape for a Swift string literal.
ESCAPED="$(printf '%s' "${BRANCH}" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"

if [[ "${BRANCH}" == "test" ]]; then
  IS_TEST="true"
else
  IS_TEST="false"
fi

mkdir -p "$(dirname "${OUT}")"
cat > "${OUT}" <<EOF
// Generated by Scripts/generate-build-channel.sh — do not edit.
enum BuildChannel {
    /// Git branch name at last build.
    static let gitBranch: String = "${ESCAPED}"
    /// True only when building from the \`test\` branch.
    static let isTestBranch: Bool = ${IS_TEST}
}
EOF

echo "BuildChannel: branch=${BRANCH} isTestBranch=${IS_TEST}"
